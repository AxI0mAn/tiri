/**
 * @file src/lib/store/toastStore.svelte.js
 * @module toastStore
 *
 * Глобальное состояние уведомлений (Toast) на рунах Svelte 5.
 *
 * Стор — синглтон: экспортируется один экземпляр `toastStore`, который
 * импортируется любым компонентом. Поля `visible`, `message`, `type`
 * реактивны (`$state`), поэтому UI-компонент тоста может подписаться
 * на них напрямую: `{#if toastStore.visible}`.
 *
 * ⚠️ Состояние **глобальное**: оно переживает навигацию между роутами
 * и размонтирование компонентов. Если показать тост и перейти на другую
 * страницу — тост останется видимым, пока кто-то не вызовет `hide()`.
 * Это осознанно: тост — часть слоя уведомлений, а не конкретной страницы.
 *
 * ⚠️ Автоскрытия нет. `show()` только выставляет `visible = true`.
 * Таймер скрытия должен ставить потребитель (обычно — сам компонент
 * `<Toast>` в `$effect`), либо это добавится позже в стор.
 *
 * Требует `.svelte.js`-расширения: руны (`$state`) не работают в обычных
 * `.js`-модулях. 
 */

/**
 * Стор уведомлений. Экземпляр-синглтон, см. `toastStore` ниже.
 *
 * Не создавайте `new ToastStore()` в компонентах — используйте готовый
 * `toastStore`, иначе получите несколько независимых состояний и
 * «пропавшие» уведомления.
 */
class ToastStore {
  /**
   * Видимость тоста. `true` — компонент тоста должен быть отрисован.
   * @type {boolean}
   */
  visible = $state(false);

  /**
   * Текст текущего уведомления. Обновляется `show()`.
   * @type {string}
   */
  message = $state('');

  /**
   * Тип уведомления — управляет стилем (цвет, иконка) в компоненте тоста.
   * @type {'success' | 'error' | 'info' | 'warning'}
   */
  type = $state('info');

  /**
   * Показать уведомление.
   *
   * Перезаписывает текущие `message` и `type` и выставляет `visible = true`.
   * Если тост уже видим — просто заменяет содержимое, без анимации
   * «скрыть-показать». Таймер автоскрытия здесь **не** ставится —
   * см. предупреждение в шапке модуля.
   *
   * @param {string} message - текст уведомления
   * @param {'success' | 'error' | 'info' | 'warning'} [type='info'] - тип уведомления
   * @returns {void}
   *
   * @example
   * import { toastStore } from '$lib/store/toastStore.svelte.js';
   *
   * toastStore.show('Запись сохранена', 'success');
   * toastStore.show('Не удалось загрузить данные', 'error');
   */
  show(message, type = 'info') {
    this.message = message;
    this.type = type;
    this.visible = true;
  }

  /**
   * Скрыть уведомление.
   *
   * Выставляет `visible = false`. `message` и `type` **не** сбрасываются —
   * это позволяет анимации исчезновения доиграть с тем же содержимым,
   * а также оставить последнее сообщение доступным для отладки.
   *
   * @returns {void}
   *
   * @example
   * // Обычно вызывается из компонента <Toast> по таймеру
   * setTimeout(() => toastStore.hide(), 3000);
   */
  hide() {
    this.visible = false;
  }
}

/**
 * Готовый синглтон-экземпляр стора.
 *
 * Импортируйте его, а не класс: `import { toastStore } from '...'`.
 * Все компоненты, использующие `toastStore`, работают с одним и тем же
 * состоянием — это и есть цель стора.
 *
 * @type {ToastStore}
 */
export const toastStore = new ToastStore();